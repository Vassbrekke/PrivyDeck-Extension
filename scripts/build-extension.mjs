function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function copyTree(outDir) {
  ensureDir(outDir);
  ensureDir(path.join(outDir, "rules"));
  ensureDir(path.join(outDir, "icons"));
  for (const rel of COPY_FILES) {
    fs.copyFileSync(path.join(sourceDir, rel), path.join(outDir, rel));
  }
}

function writeConfig(outDir) {
  fs.copyFileSync(path.join(sourceDir, "hub.js"), path.join(outDir, "hub.js"));
  const uniqueOrigins = hubOrigins();

  const config = `/** Generated by scripts/build-extension.mjs */
import { PRIVYDECK_HUB_URL } from "./hub.js";

export const PRIVYDECK_EXTENSION_CONFIG = {
  defaultHubUrl: ${devMode ? JSON.stringify(hubUrl) : "PRIVYDECK_HUB_URL"},
  allowedHubOrigins: ${JSON.stringify(uniqueOrigins)},
};
`;
  fs.writeFileSync(path.join(outDir, "config.js"), config);
}

function originPattern(origin) {
  return `${origin}/*`;
}

function expandLocalOrigins(origin) {
  try {
    const url = new URL(origin);
    const port = url.port || (url.protocol === "https:" ? "443" : "80");
    const origins = [url.origin];
    if (url.hostname === "localhost") {
      origins.push(`${url.protocol}//127.0.0.1:${port}`);
    } else if (url.hostname === "127.0.0.1") {
      origins.push(`${url.protocol}//localhost:${port}`);
    }
    return [...new Set(origins)];
  } catch {
    return [origin];
  }
}

function hubOrigins() {
  if (!devMode) return PRODUCTION_HUB_ORIGINS;
  return [...new Set([...expandLocalOrigins(hubOrigin), "http://localhost:3010", "http://127.0.0.1:3010"])];
}

function wsHostPermissions() {
  if (devMode) return ["ws://localhost:3011/*", "ws://127.0.0.1:3011/*"];
  return ["wss://ws.privydeck.com/*"];
}

function buildChromiumManifest() {
  const manifest = JSON.parse(fs.readFileSync(path.join(sourceDir, "manifest.json"), "utf8"));
  const origins = hubOrigins();
  const patterns = [...new Set(origins.map(originPattern))];
  const wsPatterns = wsHostPermissions();

  // Keep cosmetics registered in packaged builds (source manifest has both scripts).
  manifest.content_scripts = [
    { matches: patterns, js: ["content-bridge.js"], run_at: "document_idle" },
    {
      matches: ["http://*/*", "https://*/*"],
      exclude_matches: patterns,
      js: ["content-cosmetic.js"],
      run_at: "document_start",
      all_frames: true,
      match_about_blank: true,
    },
  ];
  manifest.externally_connectable = { matches: patterns };
  manifest.host_permissions = devMode
    ? ["http://localhost:*/*", "http://127.0.0.1:*/*", "https://*/*", ...wsPatterns]
    : [...patterns, "https://*/*", ...wsPatterns];

  return manifest;
}

function buildFirefoxManifest(chromiumManifest) {
  const manifest = structuredClone(chromiumManifest);
  const worker = manifest.background.service_worker;
  manifest.background = {
    scripts: [worker],
    service_worker: worker,
    type: manifest.background.type || "module",
  };
  delete manifest.externally_connectable;
  // Firefox still supports blocking webRequest for fuller filtering.
  const perms = new Set(manifest.permissions || []);
  perms.add("webRequest");
  perms.add("webRequestBlocking");
  perms.add("dns");
  manifest.permissions = [...perms];
  manifest.browser_specific_settings = {
    gecko: {
      id: firefoxId,
      strict_min_version: "113.0",
      data_collection_permissions: {
        required: ["none"],
        optional: ["authenticationInfo", "technicalAndInteraction"],
      },
    },
    gecko_android: {
      strict_min_version: "113.0",
    },
  };
  return manifest;
}

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) {
    c ^= buf[i];
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  }
  return (c ^ 0xffffffff) >>> 0;
}

function zipDirectory(dir, zipPath) {
  const files = [];
  function walk(relDir) {
    for (const entry of fs.readdirSync(path.join(dir, relDir), { withFileTypes: true })) {
      const rel = relDir ? `${relDir}/${entry.name}` : entry.name;
      if (entry.isDirectory()) walk(rel);
      else files.push(rel);
    }
  }
  walk("");

  const localParts = [];
  const centralParts = [];
  let offset = 0;

  for (const rel of files.sort()) {
    const data = fs.readFileSync(path.join(dir, rel));
    const name = Buffer.from(rel.replace(/\\/g, "/"), "utf8");
    const checksum = crc32(data) >>> 0;

    const localHeader = Buffer.alloc(30 + name.length);
    localHeader.writeUInt32LE(0x04034b50, 0);
    localHeader.writeUInt16LE(20, 4);
    localHeader.writeUInt16LE(0, 6);
    localHeader.writeUInt16LE(0, 8);
    localHeader.writeUInt16LE(0, 10);
    localHeader.writeUInt16LE(0, 12);
    localHeader.writeUInt32LE(checksum, 14);
    localHeader.writeUInt32LE(data.length, 18);
    localHeader.writeUInt32LE(data.length, 22);
    localHeader.writeUInt16LE(name.length, 26);
    localHeader.writeUInt16LE(0, 28);
    name.copy(localHeader, 30);
    localParts.push(localHeader, data);

    const centralHeader = Buffer.alloc(46 + name.length);
    centralHeader.writeUInt32LE(0x02014b50, 0);
    centralHeader.writeUInt16LE(20, 4);
    centralHeader.writeUInt16LE(20, 6);
    centralHeader.writeUInt16LE(0, 8);
    centralHeader.writeUInt16LE(0, 10);
    centralHeader.writeUInt16LE(0, 12);
    centralHeader.writeUInt16LE(0, 14);
    centralHeader.writeUInt32LE(checksum, 16);
    centralHeader.writeUInt32LE(data.length, 20);
    centralHeader.writeUInt32LE(data.length, 24);
    centralHeader.writeUInt16LE(name.length, 28);
    centralHeader.writeUInt16LE(0, 30);
    centralHeader.writeUInt16LE(0, 32);
    centralHeader.writeUInt16LE(0, 34);
    centralHeader.writeUInt16LE(0, 36);
    centralHeader.writeUInt32LE(0, 38);
    centralHeader.writeUInt32LE(offset, 42);
    name.copy(centralHeader, 46);
    centralParts.push(centralHeader);

    offset += localHeader.length + data.length;
  }

  const localData = Buffer.concat(localParts);
  const centralDir = Buffer.concat(centralParts);
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0);
  eocd.writeUInt16LE(0, 4);
  eocd.writeUInt16LE(0, 6);
  eocd.writeUInt16LE(files.length, 8);
  eocd.writeUInt16LE(files.length, 10);
  eocd.writeUInt32LE(centralDir.length, 12);
  eocd.writeUInt32LE(localData.length, 16);
  eocd.writeUInt16LE(0, 20);

  fs.writeFileSync(zipPath, Buffer.concat([localData, centralDir, eocd]));
}

function buildVariant(name, manifest) {
  const outDir = path.join(root, "dist", `extension-${name}`);
  fs.rmSync(outDir, { recursive: true, force: true });
  copyTree(outDir);
  writeConfig(outDir);
  fs.writeFileSync(path.join(outDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

  const zipPath = path.join(root, "dist", `privy-deck-extension-${name}.zip`);
  ensureDir(path.dirname(zipPath));
  zipDirectory(outDir, zipPath);
  console.log(`Built ${outDir}`);
  console.log(`Package ${zipPath}`);
}

